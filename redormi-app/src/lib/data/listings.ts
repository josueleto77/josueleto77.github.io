function buildAvailability(seedId: string): AvailabilityWindow[] {
  // A couple of listings show a blocked window to exercise calendar UI.
  if (seedId === "kyoto-machiya-house") {
    return [{ start: addDays(isoToday(), 5), end: addDays(isoToday(), 9), blocked: true }];
  }
  if (seedId === "paris-marais-apartment") {
    return [{ start: addDays(isoToday(), 12), end: addDays(isoToday(), 16), blocked: true }];
  }
  return [];
}

